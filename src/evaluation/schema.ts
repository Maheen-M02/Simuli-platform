import { z } from 'zod';
import { CustomerVerdictSchema } from './verdict.ts';

/**
 * What we report back about a run.
 *
 * The load-bearing decision is `classification`. Every finding must say what
 * kind of thing it is, and the two that are our own fault are named as such:
 *
 *  - PRODUCT_ISSUE          the product made this hard, or broke.
 *  - AGENT_MISUNDERSTANDING our simulated customer got it wrong. Our fault.
 *  - ENVIRONMENT_ERROR      the simulation or the browser broke. Our fault.
 *  - INCONCLUSIVE           something happened; the evidence will not say what.
 *
 * INCONCLUSIVE is not a failure state, it is the honest answer to a thin run,
 * and it exists so that "we do not know" has somewhere to go other than into a
 * confident claim about a customer's product. A report that quietly bills our
 * own failures to the product is worthless the first time anyone checks one.
 *
 * `evidenceRefs` is the mechanism, not a formality. A finding must cite facts
 * from the derived ledger (`evidence.ts`), which is generated by code from the
 * persisted record. Beliefs live in a separate id space and are inadmissible.
 * Both the refs and the classification are then checked mechanically in
 * `policy.ts` rather than trusted.
 */

export const CLASSIFICATIONS = [
  'PRODUCT_ISSUE',
  'AGENT_MISUNDERSTANDING',
  'ENVIRONMENT_ERROR',
  'INCONCLUSIVE',
] as const;
export type Classification = (typeof CLASSIFICATIONS)[number];

export const SEVERITIES = ['low', 'medium', 'high'] as const;
export type Severity = (typeof SEVERITIES)[number];

export const CONFIDENCES = ['low', 'medium', 'high'] as const;
export type Confidence = (typeof CONFIDENCES)[number];

/**
 * What sort of proof stands behind a finding.
 *
 * `AGENT_BELIEF` is included precisely so it can be rejected: a model that
 * honestly labels its evidence as a belief is demoted to INCONCLUSIVE by the
 * policy pass, rather than being silently accepted.
 */
export const EVIDENCE_TYPES = [
  /** A message the product displayed. */
  'VALIDATION_MESSAGE',
  /** What was, or was not, on the page. */
  'PAGE_CONTENT',
  /** An action's recorded success or failure. */
  'ACTION_RESULT',
  /** Movement, or the absence of it, between pages. */
  'NAVIGATION',
  /** The page not changing across steps. */
  'PAGE_STATE',
  /** A failure of our own tooling. */
  'RUNTIME_FAILURE',
  /** The customer's interpretation. Never sufficient on its own. */
  'AGENT_BELIEF',
] as const;
export type EvidenceType = (typeof EVIDENCE_TYPES)[number];

export const FindingSchema = z
  .object({
    /** One sentence naming the problem. */
    finding: z.string().min(1).max(300),
    classification: z.enum(CLASSIFICATIONS),
    severity: z.enum(SEVERITIES),
    /** Quoted or closely paraphrased from the cited facts. */
    evidence: z.string().min(1).max(2000),
    evidenceType: z.enum(EVIDENCE_TYPES),
    confidence: z.enum(CONFIDENCES),
    /** Who this would happen to. The persona under test, or a described type. */
    affectedPersona: z.string().min(1).max(200),
    /** Step indices, validated against the record. */
    supportingSteps: z.array(z.number().int().min(0)).min(1).max(20),
    /**
     * Fact ids from the derived ledger. Validated against it: a finding whose
     * refs are all unknown cannot stand as anything but INCONCLUSIVE.
     */
    evidenceRefs: z.array(z.string().regex(/^f\d+$/)).max(20),
    /**
     * The most plausible reading under which this is not a product problem.
     * Required, because a finding that cannot survive the question of what else
     * might explain it has not been thought about.
     */
    alternativeExplanation: z.string().min(1).max(1000),
    recommendation: z.string().min(1).max(1000),
  })
  .strict();

export type Finding = z.infer<typeof FindingSchema>;

/** Facts computed from the record without a model. Reproducible, and checkable. */
export const DeterministicFactsSchema = z
  .object({
    stepCount: z.number().int().min(0),
    durationMs: z.number().int().min(0),
    actionsAttempted: z.number().int().min(0),
    actionsFailed: z.number().int().min(0),
    plannerFailures: z.number().int().min(0),
    /** Count per ErrorKind, only for kinds that occurred. */
    errorsByKind: z.record(z.string(), z.number().int().min(1)),
    distinctUrls: z.number().int().min(0),
    /** URLs visited more than once — backtracking is a friction signal. */
    revisitedUrls: z.array(z.string()).max(50),
    destructiveActionsBlocked: z.number().int().min(0),
    /** True when the failure was ours, not the product's. */
    runIsTechnicallySound: z.boolean(),
  })
  .strict();

export type DeterministicFacts = z.infer<typeof DeterministicFactsSchema>;

/** A finding the policy pass changed, and why. Reported, never hidden. */
export const PolicyActionSchema = z
  .object({
    finding: z.string(),
    from: z.enum(CLASSIFICATIONS),
    to: z.enum(CLASSIFICATIONS),
    reason: z.string(),
  })
  .strict();

export type PolicyAction = z.infer<typeof PolicyActionSchema>;

export const EvaluationSchema = z
  .object({
    sessionId: z.string().min(1),
    /** The evaluator's verdict, judged from the facts. */
    goalAchieved: z.boolean(),
    /** Two or three sentences a product person could read on its own. */
    summary: z.string().min(1).max(3000),
    findings: z.array(FindingSchema).max(25),
    facts: DeterministicFactsSchema,
    /** Reclassifications the deterministic policy imposed on the model. */
    policyActions: z.array(PolicyActionSchema).max(25),
    /**
     * How the customer would feel. EXPERIMENTAL — see `verdict.ts`.
     *
     * Nullable because a run can fail before there is anything to feel about,
     * and because a missing verdict must never be reported as a neutral one.
     */
    customerVerdict: CustomerVerdictSchema.nullable(),
  })
  .strict();

export type Evaluation = z.infer<typeof EvaluationSchema>;

/**
 * The part the model is asked to produce; the facts and policy are ours.
 *
 * The verdict is optional here even though the assembled evaluation always
 * carries the key. It is an experimental extra, and a model that omits it has
 * still produced a usable evaluation — refusing the whole thing over a missing
 * satisfaction score would throw away the findings, which are the part that
 * matters.
 */
export const ModelEvaluationSchema = EvaluationSchema.pick({
  goalAchieved: true,
  summary: true,
  findings: true,
}).extend({
  customerVerdict: CustomerVerdictSchema.nullish().transform((value) => value ?? null),
});

export type ModelEvaluation = z.infer<typeof ModelEvaluationSchema>;

export function productIssues(evaluation: Evaluation): readonly Finding[] {
  return evaluation.findings.filter((finding) => finding.classification === 'PRODUCT_ISSUE');
}
